    private fun normalize(s: String) =
        s.replace(Regex("""[\s·!?.,:'"\u2018\u2019\u201C\u201Dー–—\-]"""), "").lowercase()

    // ── prefix 버킷 인덱스 ────────────────────────────────────────────────
    // 키를 앞 PREFIX_LEN글자로 그룹화해 미리 저장.
    // resolve 시 입력 텍스트를 PREFIX_LEN글자 슬라이딩 윈도우로 훑어
    // 매칭 가능성 있는 후보만 추출 → fuzzy 연산 대상을 ~95% 축소.
    private const val PREFIX_LEN = 5

    private val prefixIndex: Map<String, List<Pair<String, String>>> by lazy {
        val map = HashMap<String, MutableList<Pair<String, String>>>()
        for ((key, anchor) in ENCOUNTER_MAP) {
            if (key.length >= PREFIX_LEN) {
                val p = key.substring(0, PREFIX_LEN)
                map.getOrPut(p) { mutableListOf() }.add(key to anchor)
            }
        }
        map
    }


    // ── 힌트 맵 ──────────────────────────────────────────────────────────────
    fun hint(anchor: String): String? = EncounterHints.getBasic(anchor)

    fun resolve(rawText: String): ResolvedEntry? {
        val cleanInput = normalize(rawText)

        // ── 1차: prefix 인덱스로 후보 추출 후 완전 포함 매칭 ────────────
        val seen = HashSet<String>()
        var exactBestKey = ""
        var exactBestAnchor = ""

        for (start in 0..cleanInput.length - PREFIX_LEN) {
            val prefix = cleanInput.substring(start, start + PREFIX_LEN)
            val bucket = prefixIndex[prefix] ?: continue
            for ((key, anchor) in bucket) {
                if (!seen.add(key)) continue
                if (key.length >= 6 && cleanInput.contains(key) && key.length >= exactBestKey.length) {
                    exactBestKey = key
                    exactBestAnchor = anchor
                }
            }
        }

        if (exactBestKey.isNotEmpty()) {
            Log.d(TAG, "기본 인카운터 완전포함 매칭: '$exactBestAnchor' (키=${exactBestKey.take(15)}...)")
            return ResolvedEntry(
                title = exactBestAnchor,
                pageNum = "",
                type = EntryType.BASIC_ENCOUNTER,
                url = buildBasicEncounterUrl(exactBestAnchor)
            )
        }

        // ── 2차: 동일 후보들만 fuzzy 매칭 (전체 순회 없음) ───────────────
        data class FuzzyCandidate(val key: String, val anchor: String, val score: Double)

        val fuzzySeen = HashSet<String>()
        val candidates = mutableListOf<FuzzyCandidate>()

        for (start in 0..cleanInput.length - PREFIX_LEN) {
            val prefix = cleanInput.substring(start, start + PREFIX_LEN)
            val bucket = prefixIndex[prefix] ?: continue
            for ((key, anchor) in bucket) {
                if (key.length < 6) continue
                if (!fuzzySeen.add(key)) continue
                val score = fuzzyScore(cleanInput, key)
                if (score >= FUZZY_THRESHOLD) candidates.add(FuzzyCandidate(key, anchor, score))
            }
        }

        val bestScore = candidates.maxOfOrNull { it.score } ?: 0.0
        val best = candidates.lastOrNull { it.score == bestScore }

        if (best != null) {
            Log.d(TAG, "기본 인카운터 유사도 매칭: '${best.anchor}' (점수=${"%.2f".format(best.score)}, 키=${best.key.take(15)}...)")
            return ResolvedEntry(
                title = best.anchor,
                pageNum = "",
                type = EntryType.BASIC_ENCOUNTER,
                url = buildBasicEncounterUrl(best.anchor)
            )
        }

        Log.d(TAG, "기본 인카운터 매칭 실패")
        return null
    }

    // 매칭 허용 최소 점수 (0.0~1.0). 높을수록 엄격.
    private const val FUZZY_THRESHOLD = 0.70

    // ngram 크기 (trigram)
    private const val N_GRAM_SIZE = 3

    /**
     * text와 키구문(key)의 유사도 점수(0.0~1.0)를 반환.
     *
     * 두 가지 신호를 결합:
     *   A) ngram 적중률  — 글자 1~2개가 바뀌어도 나머지 조각이 살아남음
     *   B) 슬라이딩 윈도우 편집거리 — 짧은 삽입/삭제에 강함, 허용 오차를 키 길이 비례로 설정
     *
     * 최종 점수 = max(ngramScore, slideScore) 로 둘 중 하나만 잘 맞아도 통과.
     */
    private fun fuzzyScore(text: String, key: String): Double {
        // ─ A: ngram 적중률 ─────────────────────────────────────────────────
        val keyGrams = buildNgrams(key)
        if (keyGrams.isEmpty()) return 0.0
        val matchedGrams = keyGrams.count { gram -> text.contains(gram) }
        val ngramScore = matchedGrams.toDouble() / keyGrams.size

        // ─ B: 슬라이딩 윈도우 편집거리 ────────────────────────────────────
        val slideScore = bestSlideScore(text, key)

        return maxOf(ngramScore, slideScore)
    }

    /**
     * key를 N_GRAM_SIZE글자 단위 ngram 집합으로 분해.
     * ex) "서울시민" N=3 → ["서울시","울시민"]
     */
    private fun buildNgrams(s: String): List<String> {
        if (s.length < N_GRAM_SIZE) return if (s.isNotEmpty()) listOf(s) else emptyList()
        return (0..s.length - N_GRAM_SIZE).map { s.substring(it, it + N_GRAM_SIZE) }
    }

    /**
     * 텍스트(text)는 항상 key보다 길고 앞뒤로 잡음이 섞인다.
     * → window 크기를 key 길이 ± allowed 범위로 넓혀 슬라이딩.
     *
     * 허용 편집거리: key 길이의 20%
     * 점수: 1.0 - (실제거리 / 허용거리), 허용거리 초과 시 0.0
     */
    private fun bestSlideScore(text: String, key: String): Double {
        val allowed = maxOf(1, (key.length * 0.20).toInt())
        val winMin = maxOf(1, key.length - allowed)
        val winMax = key.length + allowed
        var bestDist = allowed + 1
        for (start in 0..maxOf(0, text.length - winMin)) {
            val end = minOf(text.length, start + winMax)
            if (end - start < winMin) break
            val window = text.substring(start, end)
            val d = editDistance(window, key, allowed)
            if (d < bestDist) bestDist = d
            if (bestDist == 0) break
        }
        if (bestDist > allowed) return 0.0
        return maxOf(0.0, 1.0 - bestDist.toDouble() / allowed)
    }

    private fun editDistance(a: String, b: String, rowExit: Int): Int {
        if (a == b) return 0
        if (a.isEmpty()) return b.length
        if (b.isEmpty()) return a.length
        val prev = IntArray(b.length + 1) { it }
        val curr = IntArray(b.length + 1)
        for (i in 1..a.length) {
            curr[0] = i
            var rowMin = curr[0]
            for (j in 1..b.length) {
                curr[j] = if (a[i - 1] == b[j - 1]) prev[j - 1]
                else 1 + minOf(prev[j], curr[j - 1], prev[j - 1])
                if (curr[j] < rowMin) rowMin = curr[j]
            }
            if (rowMin > rowExit) return rowExit + 1
            prev.indices.forEach { prev[it] = curr[it] }
        }
        return curr[b.length]
    }

    private fun buildBasicEncounterUrl(anchor: String): String {
        val basePath = URLEncoder.encode("서울 2033/$BASE_PATH", "UTF-8").replace("+", "%20")
        val anchorEncoded = URLEncoder.encode(anchor, "UTF-8").replace("+", "%20")
        return "$BASE/w/$basePath#$anchorEncoded"
    }
